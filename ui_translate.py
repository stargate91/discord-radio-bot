_radio_ref = None

def init_translate(radio_instance):
    global _radio_ref
    _radio_ref = radio_instance


def t(key):
    lang = "en"
    if _radio_ref:
        lang = getattr(_radio_ref, "language", "en")


    current_locales = LOCALES.get(lang, LOCALES["en"])
    result = current_locales.get(key)

    if result is None:
        result = LOCALES["en"].get(key, key)

    return result
